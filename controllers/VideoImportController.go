var importAssetNamePattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,119}$`)
var importQualityPattern = regexp.MustCompile(`^[0-9]{3,4}p$`)

type createVideoImportRequest struct {
	// RequestID is generated and persisted by the importer before the first request.
	// Go generates ImportKey, FileUUID, and LinkUUID after accepting the request.
	RequestID      string                `json:"request_id" validate:"required,min=36,max=36"`
	EmbedURL       string                `json:"embed_url,omitempty" validate:"omitempty,max=255"`
	Name           string                `json:"name" validate:"required,min=1,max=128"`
	ParentFolderID uint                  `json:"parent_folder_id"`
	Size           int64                 `json:"size" validate:"required,gt=0"`
	Duration       float64               `json:"duration" validate:"required,gt=0,lte=36000"`
	Width          int64                 `json:"width" validate:"omitempty,gte=0,lte=8000"`
	Height         int64                 `json:"height" validate:"omitempty,gte=0,lte=8000"`
	AvgFrameRate   float64               `json:"avg_frame_rate"`
	Thumbnail      string                `json:"thumbnail,omitempty"`
	QualityName    string                `json:"quality_name,omitempty"`
	Subtitles      []videoImportSubtitle `json:"subtitles,omitempty"`
}

type videoImportSubtitle struct {
	Name     string `json:"name" validate:"required,min=1,max=120"`
	Lang     string `json:"lang,omitempty" validate:"omitempty,max=10"`
	Filename string `json:"filename" validate:"required,min=1,max=120"`
	Type     string `json:"type,omitempty" validate:"omitempty,oneof=vtt"`
}

type videoImportAssetPath struct {
	Filename string `json:"filename"`
	Relative string `json:"relative_path"`
}

type videoImportSubtitleResponse struct {
	UUID     string `json:"uuid"`
	Name     string `json:"name"`
	Filename string `json:"filename"`
	Relative string `json:"relative_path"`
}

type createVideoImportResponse struct {
	RequestID string                        `json:"request_id"`
	ImportKey string                        `json:"import_key"`
	LinkUUID  string                        `json:"link_uuid"`
	FileUUID  string                        `json:"file_uuid"`
	Quality   string                        `json:"quality"`
	Video     videoImportAssetPath          `json:"video"`
	Thumbnail *videoImportAssetPath         `json:"thumbnail,omitempty"`
	Subtitles []videoImportSubtitleResponse `json:"subtitles"`
	Existing  bool                          `json:"existing"`
}

// CreateVideoImport creates a pending direct-MP4 asset without invoking the existing
// upload, encoding, or publishing pipelines. RequestID is the caller's durable retry ID;
// the canonical import/media UUIDs are generated by Go and stored in VideoImports.
func (h *Handlers) CreateVideoImport(c echo.Context) error {
	var req createVideoImportRequest
	if status, err := helpers.Validate(c, &req); err != nil {
		return c.JSON(status, echo.Map{"error": err.Error()})
	}
	parsedRequestID, err := uuid.Parse(req.RequestID)
	if err != nil || parsedRequestID.String() != strings.ToLower(req.RequestID) {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "request_id must be a UUID"})
	}
	sourceEmbedURL := strings.TrimSpace(req.EmbedURL)
	sourceEmbedKey := ""
	if sourceEmbedURL != "" {
		sourceEmbedKey, err = canonicalStreamingPlayEmbedURL(sourceEmbedURL)
		if err != nil {
			return c.JSON(http.StatusBadRequest, echo.Map{"error": "embed_url must be a StreamingPlay /embed/<id> URL"})
		}
	}
	if strings.TrimSpace(req.Name) == "" || strings.ContainsAny(req.Name, "\x00\r\n") {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "invalid name"})
	}
	if req.Thumbnail != "" && !importAssetNamePattern.MatchString(req.Thumbnail) {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "invalid thumbnail filename"})
	}
	qualityName := req.QualityName
	if qualityName == "" {
		qualityName = "720p"
	}
	if !importQualityPattern.MatchString(qualityName) {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "quality_name must look like 720p"})
	}
	for _, sub := range req.Subtitles {
		if !importAssetNamePattern.MatchString(sub.Filename) || !strings.EqualFold(filepath.Ext(sub.Filename), ".vtt") {
			return c.JSON(http.StatusBadRequest, echo.Map{"error": "subtitle filenames must be safe .vtt filenames"})
		}
		if sub.Type != "" && sub.Type != "vtt" {
			return c.JSON(http.StatusBadRequest, echo.Map{"error": "only VTT subtitles are supported by this importer"})
		}
	}
	userID, ok := c.Get("UserID").(uint)
	if !ok || userID == 0 {
		return c.JSON(http.StatusUnauthorized, echo.Map{"error": "authenticated user is missing"})
	}
	if req.ParentFolderID > 0 {
		var folder models.Folder
		if err := h.Deps.DB.Where("id = ? AND user_id = ?", req.ParentFolderID, userID).First(&folder).Error; err != nil {
			return c.JSON(http.StatusBadRequest, echo.Map{"error": "parent folder does not exist or is not owned by this user"})
		}
	}

	var response createVideoImportResponse
	requestMismatch := false
	err = h.Deps.DB.Transaction(func(tx *gorm.DB) error {
		var existing models.VideoImport
		lookup := tx.Where("user_id = ? AND request_id = ?", userID, parsedRequestID.String()).First(&existing)
		if lookup.Error == nil {
			if sourceEmbedKey != "" && existing.SourceEmbedKey != "" && existing.SourceEmbedKey != sourceEmbedKey {
				requestMismatch = true
				return errors.New("request_id is already associated with a different embed_url")
			}
			if sourceEmbedKey != "" && existing.SourceEmbedKey == "" {
				if err := tx.Model(&existing).Updates(map[string]any{"source_embed_url": sourceEmbedURL, "source_embed_key": sourceEmbedKey}).Error; err != nil {
					return err
				}
				existing.SourceEmbedURL = sourceEmbedURL
				existing.SourceEmbedKey = sourceEmbedKey
			}
			var err error
			response, err = h.loadVideoImportResponse(tx, existing, true)
			return err
		}
		if !errors.Is(lookup.Error, gorm.ErrRecordNotFound) {
			return lookup.Error
		}

		root := h.Config().PublishedQualitysRoot()
		fileUUID, linkUUID, importKey := uuid.NewString(), uuid.NewString(), uuid.NewString()
		thumbnail := req.Thumbnail
		file := models.File{
			UUID: fileUUID, Thumbnail: thumbnail,
			Size: req.Size, Duration: req.Duration, Width: req.Width, Height: req.Height,
			AvgFrameRate: req.AvgFrameRate, Path: filepath.Join(root, fileUUID, qualityName, "video.mp4"),
			Folder: filepath.Join(root, fileUUID), UserID: userID, SubtitleMode: "soft",
		}
		if len(req.Subtitles) == 0 {
			file.SubtitleMode = "none"
		}
		if err := tx.Create(&file).Error; err != nil {
			return err
		}
		link := models.Link{UUID: linkUUID, Name: strings.TrimSpace(req.Name), Thumbnail: "", ParentFolderID: req.ParentFolderID, UserID: userID, FileID: file.ID}
		if err := tx.Create(&link).Error; err != nil {
			return err
		}
		quality := models.Quality{
			Name: qualityName, Height: req.Height, Width: req.Width, Size: req.Size, FileID: file.ID,
			Type: "mp4", Muted: false, AvgFrameRate: req.AvgFrameRate,
			Path: filepath.Join(root, fileUUID, qualityName), OutputFile: "video.mp4", Ready: false,
		}
		if err := tx.Create(&quality).Error; err != nil {
			return err
		}
		for i, subReq := range req.Subtitles {
			subUUID := uuid.NewString()
			lang := subReq.Lang
			if lang == "" {
				lang = "id"
			}
			subName := strings.TrimSpace(subReq.Name)
			if subName == "" {
				subName = fmt.Sprintf("Subtitle %d", i+1)
			}
			sub := models.Subtitle{
				UUID: subUUID, Name: subName, Lang: lang, Index: -1, Codec: "webvtt", Type: "vtt",
				OutputFile: subReq.Filename, Path: filepath.Join(root, fileUUID, subUUID), FileID: file.ID,
				Ready: false, Source: "external",
			}
			if err := tx.Create(&sub).Error; err != nil {
				return err
			}
		}
		videoImport := models.VideoImport{
			UserID: userID, RequestID: parsedRequestID.String(), ImportKey: importKey,
			SourceEmbedURL: sourceEmbedURL, SourceEmbedKey: sourceEmbedKey,
			FileUUID: fileUUID, LinkUUID: linkUUID, Status: "pending",
		}
		if err := tx.Create(&videoImport).Error; err != nil {
			return err
		}
		response, err = h.loadVideoImportResponse(tx, videoImport, false)
		return err
	})
	if err != nil {
		if requestMismatch {
			return c.JSON(http.StatusConflict, echo.Map{"error": "request_id is already associated with a different embed_url"})
		}
		// A concurrent retry may have won the unique request-ID insert. Read its committed
		// result after the failed transaction rather than returning a duplicate record set.
		var existing models.VideoImport
		if lookupErr := h.Deps.DB.Where("user_id = ? AND request_id = ?", userID, parsedRequestID.String()).First(&existing).Error; lookupErr == nil {
			if existingResponse, responseErr := h.loadVideoImportResponse(h.Deps.DB, existing, true); responseErr == nil {
				return c.JSON(http.StatusOK, existingResponse)
			}
		}
		c.Logger().Errorf("create video import failed: %v", err)
		return c.JSON(http.StatusInternalServerError, echo.Map{"error": "failed to create import records"})
	}
	status := http.StatusCreated
	if response.Existing {
		status = http.StatusOK
	}
	return c.JSON(status, response)
}

func (h *Handlers) loadVideoImportResponse(db *gorm.DB, record models.VideoImport, existing bool) (createVideoImportResponse, error) {
	var file models.File
	if err := db.Where("uuid = ? AND user_id = ?", record.FileUUID, record.UserID).First(&file).Error; err != nil {
		return createVideoImportResponse{}, err
	}
	var link models.Link
	if err := db.Where("uuid = ? AND file_id = ? AND user_id = ?", record.LinkUUID, file.ID, record.UserID).First(&link).Error; err != nil {
		return createVideoImportResponse{}, err
	}
	var quality models.Quality
	if err := db.Where("file_id = ? AND type = ?", file.ID, "mp4").First(&quality).Error; err != nil {
		return createVideoImportResponse{}, err
	}
	response := h.buildVideoImportResponse(file, link, quality, record.RequestID, record.ImportKey, existing)
	var subtitles []models.Subtitle
	if err := db.Where("file_id = ?", file.ID).Order("id asc").Find(&subtitles).Error; err != nil {
		return createVideoImportResponse{}, err
	}
	for _, sub := range subtitles {
		response.Subtitles = append(response.Subtitles, videoImportSubtitleResponse{
			UUID: sub.UUID, Name: sub.Name, Filename: sub.OutputFile,
			Relative: filepath.ToSlash(filepath.Join(file.UUID, sub.UUID, sub.OutputFile)),
		})
	}
	return response, nil
}

func (h *Handlers) buildVideoImportResponse(file models.File, link models.Link, quality models.Quality, requestID, importKey string, existing bool) createVideoImportResponse {
	resp := createVideoImportResponse{
		RequestID: requestID, ImportKey: importKey, LinkUUID: link.UUID, FileUUID: file.UUID,
		Quality: quality.Name, Existing: existing, Subtitles: []videoImportSubtitleResponse{},
		Video: videoImportAssetPath{Filename: quality.OutputFile, Relative: filepath.ToSlash(filepath.Join(file.UUID, quality.Name, quality.OutputFile))},
	}
	if file.Thumbnail != "" {
		resp.Thumbnail = &videoImportAssetPath{Filename: file.Thumbnail, Relative: filepath.ToSlash(filepath.Join(file.UUID, file.Thumbnail))}
	}
	return resp
}

type completeVideoImportRequest struct {
	ImportKey string `json:"import_key"`
}

// CompleteVideoImport validates downloaded assets and marks the existing records ready.
// Repeating this call is safe: it updates the same quality/subtitle/import rows.
func (h *Handlers) CompleteVideoImport(c echo.Context) error {
	key := c.Param("key")
	if _, err := uuid.Parse(key); err != nil {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "invalid import key"})
	}
	var req completeVideoImportRequest
	if c.Request().Body != nil && c.Request().ContentLength != 0 {
		if err := c.Bind(&req); err != nil {
			return c.JSON(http.StatusBadRequest, echo.Map{"error": "invalid JSON request"})
		}
	}
	if req.ImportKey != "" && req.ImportKey != key {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "path key and import_key do not match"})
	}
	userID, ok := c.Get("UserID").(uint)
	if !ok || userID == 0 {
		return c.JSON(http.StatusUnauthorized, echo.Map{"error": "authenticated user is missing"})
	}
	var videoImport models.VideoImport
	if err := h.Deps.DB.Where("user_id = ? AND import_key = ?", userID, key).First(&videoImport).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return c.JSON(http.StatusNotFound, echo.Map{"error": "import not found"})
		}
		return c.JSON(http.StatusInternalServerError, echo.Map{"error": "failed to load import"})
	}
	
	// Calculate the hash from the final MP4 before opening the main
	// database transaction. Avoid hashing the video again on retries.
	var hashForFile string

	var importedLink models.Link
	if err := h.Deps.DB.
		Preload("File").
		Preload("File.Qualitys").
		Where("uuid = ? AND user_id = ?", videoImport.LinkUUID, userID).
		First(&importedLink).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return c.JSON(http.StatusNotFound, echo.Map{
				"error": "imported video not found",
			})
		}
		return c.JSON(http.StatusInternalServerError, echo.Map{
			"error": "failed to load imported video",
		})
	}

	if strings.TrimSpace(importedLink.File.Hash) == "" {
		var mp4ForHash *models.Quality

		for i := range importedLink.File.Qualitys {
			if importedLink.File.Qualitys[i].Type == "mp4" {
				mp4ForHash = &importedLink.File.Qualitys[i]
				break
			}
		}

		if mp4ForHash == nil {
			return c.JSON(http.StatusConflict, echo.Map{
				"error": "direct MP4 quality record is missing",
			})
		}

		root := h.Config().PublishedQualitysRoot()
		videoPath := filepath.Join(
			root,
			importedLink.File.UUID,
			mp4ForHash.Name,
			mp4ForHash.OutputFile,
		)

		videoInfo, err := os.Stat(videoPath)
		if err != nil || !videoInfo.Mode().IsRegular() || videoInfo.Size() <= 0 {
			return c.JSON(http.StatusConflict, echo.Map{
				"error": "video file is missing or empty",
			})
		}

		hashForFile, err = helpers.HashFile(videoPath)
		if err != nil {
			c.Logger().Errorf("Failed to hash imported MP4: %v", err)
			return c.JSON(http.StatusInternalServerError, echo.Map{
				"error": "failed to calculate video hash",
			})
		}
	}
	
	var link models.Link
	err := h.Deps.DB.Transaction(func(tx *gorm.DB) error {
		if err := tx.Preload("File").Preload("File.Qualitys").Preload("File.Subtitles").Where("uuid = ? AND user_id = ?", videoImport.LinkUUID, userID).First(&link).Error; err != nil {
			return err
		}
		root := h.Config().PublishedQualitysRoot()
		var mp4 *models.Quality
		for i := range link.File.Qualitys {
			if link.File.Qualitys[i].Type == "mp4" {
				mp4 = &link.File.Qualitys[i]
				break
			}
		}
		if mp4 == nil {
			return errors.New("direct MP4 quality record is missing")
		}
		videoPath := filepath.Join(root, link.File.UUID, mp4.Name, mp4.OutputFile)
		videoInfo, err := os.Stat(videoPath)
		if err != nil || !videoInfo.Mode().IsRegular() || videoInfo.Size() <= 0 {
			return errors.New("video file is missing or empty")
		}
		if link.File.Thumbnail != "" {
			thumbInfo, err := os.Stat(filepath.Join(root, link.File.UUID, link.File.Thumbnail))
			if err != nil || !thumbInfo.Mode().IsRegular() {
				return errors.New("thumbnail file is missing")
			}
		}
		for _, sub := range link.File.Subtitles {
			if _, err := os.Stat(filepath.Join(root, link.File.UUID, sub.UUID, sub.OutputFile)); err != nil {
				return fmt.Errorf("subtitle %s is missing", sub.Name)
			}
		}
		if err := tx.Model(&models.Quality{}).Where("id = ?", mp4.ID).Updates(map[string]any{"ready": true, "size": videoInfo.Size(), "encoding": false, "publishing": false, "failed": false, "error": "", "progress": 100}).Error; err != nil {
			return err
		}
		for _, sub := range link.File.Subtitles {
			if err := tx.Model(&models.Subtitle{}).Where("id = ?", sub.ID).Updates(map[string]any{"ready": true, "failed": false, "error": "", "progress": 100}).Error; err != nil {
				return err
			}
		}
		fileUpdates := map[string]any{"size": videoInfo.Size(),}

		if hashForFile != "" {fileUpdates["hash"] = hashForFile}

		if err := tx.Model(&models.File{}).
			Where("id = ?", link.FileID).
			Updates(fileUpdates).Error; err != nil {
			return err
		}
		return tx.Model(&models.VideoImport{}).Where("id = ?", videoImport.ID).Update("status", "ready").Error
	})
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return c.JSON(http.StatusNotFound, echo.Map{"error": "import not found"})
		}
		return c.JSON(http.StatusConflict, echo.Map{"error": err.Error()})
	}
	return c.JSON(http.StatusOK, echo.Map{"request_id": videoImport.RequestID, "import_key": key, "link_uuid": link.UUID, "file_uuid": link.File.UUID, "ready": true})
}

// canonicalStreamingPlayEmbedURL validates and normalizes the legacy embed URL so
// importer retries and WordPress lookups use one stable representation.
func canonicalStreamingPlayEmbedURL(raw string) (string, error) {
	parsed, err := url.Parse(strings.TrimSpace(raw))
	if err != nil || parsed == nil {
		return "", errors.New("invalid URL")
	}
	if parsed.Scheme != "https" && parsed.Scheme != "http" {
		return "", errors.New("unsupported scheme")
	}
	host := strings.ToLower(parsed.Hostname())
	if host != "streamingplay.biz" && host != "www.streamingplay.biz" {
		return "", errors.New("unsupported host")
	}
	if parsed.User != nil || parsed.Port() != "" || parsed.RawQuery != "" || parsed.Fragment != "" {
		return "", errors.New("unexpected URL components")
	}
	parts := strings.Split(strings.Trim(parsed.Path, "/"), "/")
	if len(parts) != 2 || parts[0] != "embed" || !regexp.MustCompile(`^[A-Za-z0-9_-]{4,100}$`).MatchString(parts[1]) {
		return "", errors.New("invalid embed path")
	}
	return "https://streamingplay.biz/embed/" + parts[1], nil
}

type resolveImportedIframeResponse struct {
	EmbedURL string `json:"embed_url"`
	LinkUUID string `json:"link_uuid"`
	Iframe   string `json:"iframe"`
}

// ResolveImportedIframe is intentionally public for the one-time WordPress migration.
// It only returns links for completed imports and accepts only validated StreamingPlay URLs.
func (h *Handlers) ResolveImportedIframe(c echo.Context) error {
	raw := c.QueryParam("embedUrl")
	if raw == "" {
		raw = c.QueryParam("embed_url")
	}
	canonicalURL, err := canonicalStreamingPlayEmbedURL(raw)
	if err != nil {
		return c.JSON(http.StatusBadRequest, echo.Map{"error": "provide a valid StreamingPlay embedUrl"})
	}
	baseURL := strings.TrimRight(strings.TrimSpace(h.Config().BaseUrl), "/")
	if baseURL == "" {
		return c.JSON(http.StatusServiceUnavailable, echo.Map{"error": "BaseUrl is not configured"})
	}
	parsedBase, err := url.Parse(baseURL)
	if err != nil || (parsedBase.Scheme != "https" && parsedBase.Scheme != "http") || parsedBase.Host == "" || parsedBase.User != nil || parsedBase.RawQuery != "" || parsedBase.Fragment != "" {
		return c.JSON(http.StatusServiceUnavailable, echo.Map{"error": "BaseUrl is invalid"})
	}
	var imported models.VideoImport
	if err := h.Deps.DB.Where("source_embed_key = ? AND status = ?", canonicalURL, "ready").First(&imported).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return c.JSON(http.StatusNotFound, echo.Map{"error": "no completed VideoCMS import matches this embed URL"})
		}
		return c.JSON(http.StatusInternalServerError, echo.Map{"error": "failed to look up imported video"})
	}
	var link models.Link
	if err := h.Deps.DB.Where("uuid = ?", imported.LinkUUID).First(&link).Error; err != nil {
		return c.JSON(http.StatusNotFound, echo.Map{"error": "VideoCMS link not found"})
	}
	src := baseURL + "/v/" + url.PathEscape(link.UUID)
	title := "Watch " + link.Name + " on VideoCMS"
	iframe := fmt.Sprintf(`<iframe width="100%%" height="100%%" src="%s" title="%s" frameborder="0" allow="accelerometer; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen></iframe>`, htmlEscapeAttribute(src), htmlEscapeAttribute(title))
	return c.JSON(http.StatusOK, resolveImportedIframeResponse{EmbedURL: canonicalURL, LinkUUID: link.UUID, Iframe: iframe})
}

func htmlEscapeAttribute(value string) string {
	value = strings.ReplaceAll(value, "&", "&amp;")
	value = strings.ReplaceAll(value, `"`, "&quot;")
	value = strings.ReplaceAll(value, "<", "&lt;")
	value = strings.ReplaceAll(value, ">", "&gt;")
	return value
}
